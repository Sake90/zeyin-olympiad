// Hard-locked observation prompt. Inputs come from results/students/topic-perf;
// the output goes straight into the family-facing report so we constrain hard.

export interface AnalysisInput {
  full_name: string
  grade: number
  language: 'ru' | 'kk'
  score: number
  total_questions: number
  accuracy_percent: number
  subject_scores: Array<{ name: string; score: number; total: number }>
  math_topics: Array<{ name: string; percent: number }>
  behavior?: {
    speed_label: 'fast' | 'normal' | 'slow'
    confidence_label: 'high' | 'medium' | 'low'
    error_pattern: 'weak_start' | 'weak_end' | 'consistent'
    avg_seconds: number
  } | null
}

function fmtSubjects(subs: AnalysisInput['subject_scores']): string {
  if (subs.length === 0) return '(нет данных по предметам)'
  return subs.map(s => `${s.name}: ${s.score}/${s.total}`).join('; ')
}

function fmtSubjectsKk(subs: AnalysisInput['subject_scores']): string {
  if (subs.length === 0) return '(пәндер бойынша деректер жоқ)'
  return subs.map(s => `${s.name}: ${s.score}/${s.total}`).join('; ')
}

function fmtTopics(topics: AnalysisInput['math_topics']): string {
  if (topics.length === 0) return '(темы математики не размечены)'
  return topics.map(t => `${t.name} — ${Math.round(t.percent)}%`).join('; ')
}

function fmtTopicsKk(topics: AnalysisInput['math_topics']): string {
  if (topics.length === 0) return '(математика тақырыптары белгіленбеген)'
  return topics.map(t => `${t.name} — ${Math.round(t.percent)}%`).join('; ')
}

function fmtBehavior(b: AnalysisInput['behavior']): string {
  if (!b) return '(данные о поведении недоступны)'
  const speed = { fast: 'быстро', normal: 'в среднем темпе', slow: 'вдумчиво' }[b.speed_label]
  const conf  = { high: 'высокая', medium: 'средняя', low: 'разный ритм' }[b.confidence_label]
  const pat   = { weak_start: 'слабый старт, к концу освоился',
                  weak_end:   'хорошее начало, к концу устал',
                  consistent: 'стабильно от начала до конца' }[b.error_pattern]
  return `средний темп: ${speed} (${b.avg_seconds} сек/вопрос); уверенность: ${conf}; паттерн: ${pat}`
}

function fmtBehaviorKk(b: AnalysisInput['behavior']): string {
  if (!b) return '(тәртіп туралы деректер жоқ)'
  const speed = { fast: 'жылдам', normal: 'орташа', slow: 'ойланып' }[b.speed_label]
  const conf  = { high: 'жоғары', medium: 'орташа', low: 'әртүрлі ырғақ' }[b.confidence_label]
  const pat   = { weak_start: 'басында қиын болды, соңында жақсы',
                  weak_end:   'жақсы бастады, соңында шаршады',
                  consistent: 'басынан соңына дейін бірдей' }[b.error_pattern]
  return `темп: ${speed} (${b.avg_seconds} сек/сұрақ); сенімділік: ${conf}; үлгі: ${pat}`
}

